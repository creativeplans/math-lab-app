def fwd_level(n):
    """How the coverage header names a forward branch's level."""
    if n < 9:
        return 'Grade %d' % n
    return 'Common Core high-school standards, which this bank places at Grade %d as an instructional choice' % n


SECTION_ORDER = ['BACKWARD', 'MAIN', 'FORWARD 1', 'FORWARD 2']
SPECIAL = {'plot': 'drawing on a figure', 'plot_text': 'drawing + written answer', 'work': 'answer with required work'}


def run_course(name):
    """COVERAGE.md for a course collection (Algebra I): every course standard with its question counts, the difficulty
    (section) distribution, prerequisite and forward relationships, questions needing drawing, figures, or shown work,
    and the known gaps and limitations (NOTES in coverage_reqs.py)."""
    import collections
    import hs_courses
    cov = importlib.import_module('coverage_reqs')
    rows = cov.requirements()
    course = qb.COURSE['name']
    recs = json.load(open(build.out_paths()['data'] + '.json', encoding='utf-8'))['questions']
    pages = {r['id']: r['page'] for r in recs}
    sets = {st['num']: st for st in build.all_sets()}
    level = lambda sec: 'BACKWARD' if sec.startswith('BACKWARD') else sec
    L = ['# %s coverage report' % course, '',
         'Generated by `engine/coverage.py` from the collection data. %d sets, %d questions. Each set has a MAIN section (five %s '
         'questions), two backward branches (Grade K-8 standards, or an %s standard taught in an earlier set), FORWARD 1, and '
         'FORWARD 2 (standards of later courses). Every branch has five questions.' % (len(sets), len(recs), course, course), '',
         '## 1. Every %s standard' % course, '',
         'MAIN questions are the questions written to the standard. "As a backward branch" counts questions in later sets that '
         'use the standard as a prerequisite review.', '',
         '| Standard | Sets (MAIN) | MAIN questions | As a backward branch | Drawing / work questions in its MAIN sections |',
         '|---|---|---:|---:|---:|']
    by_std = collections.defaultdict(list)
    for r in recs:
        by_std[r['standard']].append(r)
    for code in qb.COURSE['standards']:
        main = [r for r in by_std[code] if r['section'] == 'MAIN']
        back = [r for r in by_std[code] if r['section'].startswith('BACKWARD')]
        nums = sorted({r['set'] for r in main})
        special = sum(1 for r in main if r['type'] in SPECIAL)
        L.append('| %s | %s | %d | %d | %d |' % (code, ', '.join('S%d' % n for n in nums) or '**none**', len(main), len(back), special))
    missing = [c for c in qb.COURSE['standards'] if not any(r['section'] == 'MAIN' for r in by_std[c])]
    L += ['', 'Standards with no MAIN set: %s.' % (', '.join(missing) if missing else 'none'), '']
    L += ['## 2. Requirements, performance tested, and branches', '',
          '| Standard | Requirement | Performance tested (MAIN) | Set | Page | Backward branches (prerequisites) | Forward 1 | Forward 2 |',
          '|---|---|---|---|---:|---|---|---|']
    for std, req, nums, perf in rows:
        for n in nums:
            st = sets[n]
            assert st['std'] == std, (n, st['std'], std)
            secs = build.sections(st)
            back = '; '.join('%s %s' % (A.section_code(k), sc) for k, _, sc, _, _ in secs if k.startswith('BACKWARD'))
            fw = {k: (sc, nm, nr) for k, nm, sc, _, nr in secs if k.startswith('FORWARD')}
            cell = lambda k: '%s (%s): %s%s' % (fw[k][0], hs_courses.course_of(fw[k][0]), fw[k][1], ' — NEAREST RELATED' if fw[k][2] else '')
            L.append('| %s | %s | %s | S%d | %d | %s | %s | %s |' % (
                std, req, perf, n, pages['S%d-M-Q1' % n], back, cell('FORWARD 1'), cell('FORWARD 2')))
    L += ['', '## 3. Difficulty distribution', '',
          'The collection has no separate difficulty field (none of the Grade 3-8 collections do). Difficulty is carried by the '
          'section: backward branches review prerequisites, MAIN is on-level %s work, FORWARD 1 and FORWARD 2 extend into later '
          'courses, FORWARD 2 never in an earlier course than FORWARD 1.' % course, '',
          '| Section level | Questions | Short answer | Multiple choice | True/false | Drawing or work |', '|---|---:|---:|---:|---:|---:|']
    for lv in SECTION_ORDER:
        rs = [r for r in recs if level(r['section']) == lv]
        t = collections.Counter(r['type'] for r in rs)
        L.append('| %s | %d | %d | %d | %d | %d |' % (lv, len(rs), t['sa'], t['mc'], t['tf'], sum(t[k] for k in SPECIAL)))
    L += ['', '## 4. Prerequisite (backward) relationships', '', '| Source of the backward standard | Branches | Questions |', '|---|---:|---:|']
    bsec = collections.Counter()
    for r in recs:
        if r['section'].startswith('BACKWARD'):
            src = 'Grade %s' % r['standard'].split('.')[0] if not r['standard'].startswith('HS') else 'Earlier %s set' % course
            bsec[src] += 1
    for k in sorted(bsec, key=lambda k: (k.startswith('Earlier'), k)):
        L.append('| %s | %d | %d |' % (k, bsec[k] // 5, bsec[k]))
    L += ['', 'Every backward %s standard is the MAIN standard of an earlier set, so a student routed backward meets a skill the '
          'collection has already taught. The build stops if a backward branch breaks this rule.' % course, '',
          '## 5. Forward relationships', '',
          'Forward standards are labeled with the course this bank places them in (`engine/hs_courses.py`); they are never labeled '
          'as %s standards. Collections for those courses do not exist yet, so forward branches carry the standard code and course '
          'name only; they reference no set or file outside this collection.' % course, '',
          '| Course | FORWARD 1 branches | FORWARD 2 branches | Distinct standards |', '|---|---:|---:|---:|']
    for c in hs_courses.COURSES[1:]:
        f1 = [st for st in sets.values() if hs_courses.course_of(st['f1']['std']) == c]
        f2 = [st for st in sets.values() if hs_courses.course_of(st['f2']['std']) == c]
        codes = {st['f1']['std'] for st in f1} | {st['f2']['std'] for st in f2}
        L.append('| %s | %d | %d | %d |' % (c, len(f1), len(f2), len(codes)))
    near = [(st['num'], key, st[k]['std'], st[k]['title'], st[k]['nearest']) for st in sets.values()
            for k, key in (('f1', 'FORWARD 1'), ('f2', 'FORWARD 2')) if st[k].get('nearest')]
    if near:
        L += ['', 'Branches marked NEAREST RELATED (no later-course standard directly continues the MAIN skill at that step); '
              'the connection is printed on the branch page and exported as `nearest_connection`:', '',
              '| Set | Branch | Standard | Skill | Connection to the MAIN skill |', '|---|---|---|---|---|']
        for n, key, sc, title, conn in sorted(near):
            L.append('| S%d | %s | %s | %s | %s |' % (n, key, sc, title, conn if isinstance(conn, str) else ''))
    L += ['', '## 6. Questions that need visual or specialized answer support', '']
    for t, desc in SPECIAL.items():
        ids = [r['id'] for r in recs if r['type'] == t]
        L.append('- **%s** (`%s`, %d): %s' % (desc[0].upper() + desc[1:], t, len(ids), ', '.join(ids)))
    figs = [r['id'] for r in recs if r['has_figure'] and r['type'] not in SPECIAL]
    L.append('- **Read a figure** (graph, table, number line, scatter plot, or histogram; answered by text, choice, or true/false; %d): %s'
             % (len(figs), ', '.join(figs)))
    tech = [r['id'] for r in recs if any(w in r['question'] for w in ('technology', 'calculator', 'Round ', 'nearest tenth', 'nearest hundredth'))]
    L.append('- **Calculator or technology expected** (%d): %s' % (len(tech), ', '.join(tech)))
    if getattr(cov, 'NOTES', None):
        L += ['', '## 7. Gaps and limitations', ''] + cov.NOTES
    path = os.path.join(build.GRADE_DIR, 'COVERAGE.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    return path, len(rows)


def run_geometry(name):
    """COVERAGE.md for the Geometry collection: every standard (core and (+)), every subskill (subpart or distinct demand)
    with the set and MAIN IDs that cover it, each set's branches with their alignment and progression metadata, and the
    known gaps (NOTES in coverage_reqs.py)."""
    import collections
    import hs_courses
    import standards
    cov = importlib.import_module('coverage_reqs')
    recs = json.load(open(build.out_paths()['data'] + '.json', encoding='utf-8'))['questions']
    pages = {r['id']: r['page'] for r in recs}
    sets = list(build.all_sets())
    by_std = collections.defaultdict(list)
    for st in sets:
        by_std[st['std']].append(st)
    L = ['# Geometry coverage report', '',
         'Generated by `engine/coverage.py` from the collection data: %d sets, %d questions. Every set has a MAIN section (five '
         'parallel questions on one target skill), 2-7 backward branches (prerequisites: Grade K-8 standards, Algebra I '
         'standards, or the MAIN standard of an earlier Geometry set), FORWARD 1, and FORWARD 2. Every section has five '
         'questions. Page numbers are the same in the Question Collection and the Answer Key.' % (len(sets), len(recs)), '']
    for strand, codes, head in (('core', hs_courses.GEOMETRY, '1. Core standards'), ('advanced', hs_courses.GEOMETRY_PLUS,
                                                                                   '2. ADVANCED EXTENSION (+) standards')):
        L += ['## %s' % head, '', '| Standard | Sets (MAIN) | MAIN questions | Subskills | Used as a backward branch |',
              '|---|---|---:|---|---:|']
        for code in codes:
            sts = by_std.get(code, [])
            nback = sum(1 for st in sets for b in st['back'] if b['std'] == code)
            subs = [sid for sid, _ in standards.STANDARDS[code][1]]
            L.append('| %s | %s | %d | %s | %d |' % (code, ', '.join('S%d' % st['num'] for st in sts) or '**none**', 5 * len(sts),
                                                    ', '.join(subs), nback))
        L.append('')
    L += ['## 3. Subparts and distinct demands', '',
          'Each standard is split into the subskills its wording names (subparts, listed objects, and verbs such as prove, '
          'construct, derive). Each subskill is the declared focus of at least one set, whose five MAIN questions test it.', '',
          '| Subskill | Standard | Demand | Set | MAIN IDs | Page | Strand |', '|---|---|---|---|---|---:|---|']
    for code, (_, subs) in standards.STANDARDS.items():
        for sid, desc in subs:
            for st in sets:
                if sid in st.get('covers', []):
                    L.append('| %s | %s | %s | S%d — %s | S%d-M-Q1 … Q5 | %d | %s |' % (
                        sid, code, desc, st['num'], st['title'], st['num'], pages['S%d-M-Q1' % st['num']],
                        'advanced (+)' if st.get('strand') == 'advanced' else 'core'))
    L += ['', '## 4. Sets and branches', '',
          'Backward: standard (exact = the standard names the prerequisite; supporting = the closest standard, as no standard '
          'names that micro-skill exactly). Forward: standard (course placement), progression type, and direct or NEAREST RELATED.', '',
          '| Set | Standard | Target skill | Backward branches | FORWARD 1 | FORWARD 2 |', '|---|---|---|---|---|---|']
    for st in sets:
        back = '; '.join('B%d %s (%s)' % (i, b['std'], b['meta']['align']) for i, b in enumerate(st['back'], 1))
        fw = lambda b: '%s (%s): %s; %s' % (b['std'], hs_courses.course_of(b['std']), b['meta']['prog'],
                                             'NEAREST RELATED' if b.get('nearest') else 'direct')
        L.append('| S%d | %s | %s | %s | %s | %s |' % (st['num'], st['std'], st['target'], back, fw(st['f1']), fw(st['f2'])))
    level = lambda sec: 'BACKWARD' if sec.startswith('BACKWARD') else sec
    L += ['', '## 5. Question distribution', '',
          'Difficulty is carried by the section: backward branches review prerequisites with easy numbers and one idea per '
          'question; MAIN is on-level Geometry; FORWARD 1 and FORWARD 2 add one stated new demand each.', '',
          '| Section | Questions | Short answer | Multiple choice | True/false | Shown work (proof, derivation, explanation) | Drawing or construction |',
          '|---|---:|---:|---:|---:|---:|---:|']
    for lv in SECTION_ORDER:
        rs = [r for r in recs if level(r['section']) == lv]
        tc = collections.Counter(r['type'] for r in rs)
        L.append('| %s | %d | %d | %d | %d | %d | %d |' % (lv, len(rs), tc['sa'], tc['mc'], tc['tf'], tc['work'], tc['plot'] + tc['plot_text']))
    src = collections.Counter()
    for st in sets:
        for b in st['back']:
            code = b['std']
            src['Grade %s' % code.split('.')[0] if not code.startswith('HS') else
                ('Algebra I' if hs_courses.course_of(code) == 'Algebra I' else 'Earlier Geometry set')] += 1
    L += ['', '## 6. Backward and forward relationships', '', '| Source of backward standard | Branches |', '|---|---:|']
    for k in sorted(src, key=lambda k: (not k.startswith('Grade'), k)):
        L.append('| %s | %d |' % (k, src[k]))
    prog = collections.Counter((k.upper(), st[k]['meta']['prog']) for st in sets for k in ('f1', 'f2'))
    L += ['', '| Branch | Progression type | Count |', '|---|---|---:|'] + ['| %s | %s | %d |' % (k, p, v) for (k, p), v in sorted(prog.items())]
    L += ['', '## 7. Questions that need visual or specialized answer support', '']
    for t, desc in (('plot', 'drawing or construction on a figure'), ('work', 'shown work: proof, derivation, or explanation with a work box')):
        ids = [r['id'] for r in recs if r['type'] == t]
        L.append('- **%s** (`%s`, %d): %s' % (desc[0].upper() + desc[1:], t, len(ids), ', '.join(ids)))
    figs = [r['id'] for r in recs if r['has_figure'] and r['type'] not in ('plot', 'work')]
    L.append('- **Read a figure** (answered by text, choice, or true/false; %d): %s' % (len(figs), ', '.join(figs)))
    if getattr(cov, 'NOTES', None):
        L += ['', '## 8. Gaps and limitations', ''] + cov.NOTES
    path = os.path.join(build.GRADE_DIR, 'COVERAGE.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    return path, len(sets)


def run(name):
    build.load_grade(name)
    if qb.COURSE and qb.COURSE.get('rules') == 'geometry':
        return run_geometry(name)
    if qb.profile_mode():  # later profile courses (Algebra II) write their report from their own src/coverage_report.py
        import importlib
        return importlib.import_module('coverage_report').run(name)
    if qb.COURSE:
        return run_course(name)
    cov = importlib.import_module('coverage_reqs')
    sets = {st['num']: st for st in build.all_sets()}
    pages = {r['id']: r['page'] for r in json.load(open(build.out_paths()['data'] + '.json', encoding='utf-8'))['questions']}
    used = set()
    lines = ['# Grade %d coverage matrix' % build.GRADE, '',
             'Each row is one distinct Grade %d requirement and the set whose MAIN section (five variations) focuses on it. '
             'Every set also has its backward (earlier-grade) branches and FORWARD 1 (%s) and FORWARD 2 (%s). '
             'Page is the MAIN section\'s first question page in the question PDF.' % (
                 build.GRADE, fwd_level(build.GRADE + 1), fwd_level(build.GRADE + 2)), '']
    perf = any(len(r) > 3 for r in cov.REQUIREMENTS)
    if perf:
        lines += ['"Performance tested" says what students actually do in the five MAIN questions.', '',
                  '| Standard | Requirement | Performance tested | Set | MAIN IDs | Page | Backward branches | Forward 1 | Forward 2 |',
                  '|---|---|---|---|---|---:|---|---|---|']
    else:
        lines += ['| Standard | Requirement | Set | MAIN IDs | Page | Backward branches | Forward 1 | Forward 2 |', '|---|---|---|---|---:|---|---|---|']
    for row in cov.REQUIREMENTS:
        std, req, nums = row[:3]
        for n in nums:
            st = sets[n]
            assert st['std'] == std, (n, st['std'], std)
            used.add(n)
            secs = build.sections(st)
            back = '; '.join('%s %s' % (A.section_code(k), s) for k, _, s, _, _ in secs if k.startswith('BACKWARD'))
            f1 = [s for k, _, s, _, _ in secs if k == 'FORWARD 1'][0]
            f2 = [s for k, _, s, _, _ in secs if k == 'FORWARD 2'][0]
            cells = [std, req] + ([row[3]] if perf else []) + [
                'S%d — %s' % (n, st['title']), 'S%d-M-Q1 … Q5' % n, str(pages['S%d-M-Q1' % n]), back, f1, f2]
            lines.append('| ' + ' | '.join(cells) + ' |')
    missing = sorted(set(sets) - used)
    assert not missing, 'sets without a requirement row: %s' % missing
    if getattr(cov, 'NOTES', None):
        lines += [''] + cov.NOTES
    path = os.path.join(build.GRADE_DIR, 'COVERAGE.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    return path, len(cov.REQUIREMENTS)


if __name__ == '__main__':
    print(run(sys.argv[1] if len(sys.argv) > 1 else 'grade5'))
