def numbers(text):
    text = text.replace('−', '-').replace(',', '')
    return [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?', text)]


def run():
    key = {r['id']: r for r in json.load(open(KEY, encoding='utf-8'))['questions']}
    bad, n = [], 0
    for qid, exp in CASES:
        r = key[qid]
        ans = r['correct_answer'] or ''
        nums = numbers(ans)
        for e in exp:
            n += 1
            if isinstance(e, str):
                if e not in ans:
                    bad.append('%s: expected "%s" in key "%s"' % (qid, e, ans))
            else:
                v, d = e
                want = round(v + 1e-12, d)
                if not any(abs(x - want) < 10 ** -d / 2 + 1e-9 for x in nums):
                    bad.append('%s: recomputed %.*f, key "%s"' % (qid, d, want, ans))
    return len(CASES), n, bad


if __name__ == '__main__':
    nq, nv, bad = run()
    print('re-solved %d questions (%d values): %d disagreements' % (nq, nv, len(bad)))
    for b in bad:
        print('  ' + b)
    sys.exit(1 if bad else 0)
