"""Write algebra2/COVERAGE.md: the course profile and its inclusion/exclusion decisions, a coverage matrix for every
standard, subpart, and subskill, the routing (branch) map of every set, and the response types used.

    python3 question-bank/engine/coverage.py algebra2      (dispatches here)
"""
import collections
import json
import os

import build
import hs_courses
import standards

# Standards a reader might expect in Algebra II, and where this collection puts them. Reasons are the bank's decisions;
# the pathway placements are stated from CCSS Appendix A as recalled (see README, "Assumptions").
EXCLUDED = [
    ('HSF-IF.C.8.a', 'Algebra I', 'The pathway lists F-IF.8 in Algebra II for its new families. Part a (completing the square to show '
                                  'zeros, extremes, symmetry of quadratics) is Algebra I work in this bank; part b (exponential rates) is CORE here.'),
    ('HSF-IF.A.3, HSF-BF.A.2, HSF-BF.A.1.a', 'Algebra I', 'Sequences and writing functions from a context are taught in the Algebra I '
                                                       'collection; Algebra II uses them only as backward branches (for example S11, S12).'),
    ('HSN-RN, HSN-Q, HSA-REI.B, HSA-REI.C.5-7, HSA-REI.D.10, HSA-REI.D.12, HSF-IF.A, HSF-LE.A.1-3, HSF-LE.B.5, '
     'HSS-ID.A.1-3, HSS-ID.B, HSS-ID.C', 'Algebra I', 'Not part of the Algebra II pathway; used here only as prerequisites (backward branches).'),
    ('HSS-CP (all)', 'Probability & Statistics', 'Appendix A places conditional probability in Geometry; this bank places it in its planned '
                                                 'Probability & Statistics course (engine/hs_courses.py). Used here only as forward branches.'),
    ('HSS-MD.A.1-4, HSS-MD.B.5 (+)', 'Probability & Statistics', 'Expected value and probability distributions are later-course '
                                                                   'extensions (forward branches of S21, S72).'),
    ('HSN-CN.B.4-6 (+), HSA-REI.C.8-9 (+), HSN-VM (+), HSF-TF.C.9 (+)', 'Precalculus', 'Official (+) standards not in the pathway and '
                                                                                    'not chosen for the extension; used only as later-course forward branches.'),
    ('HSG (all)', 'Geometry', 'Used only as prerequisites (backward branches), for example special right triangles before F-TF.'),
]


def run(name):
    recs = json.load(open(build.out_paths()['data'] + '.json', encoding='utf-8'))['questions']
    sets = list(build.all_sets())
    by_std = collections.defaultdict(list)
    for r in recs:
        by_std[r['standard']].append(r)
    page = {r['id']: r['question_page'] for r in recs}
    covers = collections.defaultdict(list)
    for st in sets:
        for sid in st['covers']:
            covers[sid].append(st['num'])
    core, adv = hs_courses.ALGEBRA_II_CORE, hs_courses.ALGEBRA_II_ADVANCED
    shared = [c for c in core if c in hs_courses.ALGEBRA_I]
    L = ['# Algebra II coverage report', '',
         'Generated by `algebra2/src/coverage_report.py` from the collection data: %d sets, %d questions. Course placement labels '
         '(not grade levels) are used throughout.' % (len(sets), len(recs)), '',
         '## 1. Course profile', '',
         '- **Baseline:** the Common Core traditional-pathway Algebra II course (CCSS Mathematics, Appendix A). %d standards form the '
         'CORE strand, including the (+) standards that the pathway lists itself (N-CN.8, N-CN.9, A-APR.5, A-APR.7, S-MD.6, S-MD.7).' % len(core),
         '- **Expansion:** %d further official (+) standards form the optional ADVANCED EXTENSION strand (strand = "advanced" in the '
         'export). This is a decision of this bank, not an official assignment.' % len(adv),
         '- **Revisited Algebra I codes:** %d CORE codes are shared with Algebra I in the pathway (%s). Their Algebra II sets assess the '
         'new demand stated in the matrix (REVISIT), not the Algebra I demand. When one of these codes is used as a backward branch it '
         'is labeled Algebra I.' % (len(shared), ', '.join(shared)),
         '- **Source caveat:** the official pages could not be opened from the authoring environment. The profile and wording were '
         'written from the published standards and must be spot-checked (README, Assumptions).', '',
         '## 2. Inclusion and exclusion table', '',
         '| Standards | Decision | Where they are | Reason |', '|---|---|---|---|',
         '| %d pathway standards (section 3, strand CORE) | Included: CORE | Algebra II, MAIN sets | CCSS Appendix A traditional-pathway Algebra II |' % len(core),
         '| %s | Included: ADVANCED EXTENSION (+) | Algebra II, MAIN sets with strand = advanced | Official (+) standards that continue '
         'Algebra II topics (complex conjugates, rational graphs, composition and inverses, inverse trigonometry); optional |' % ', '.join(adv)]
    for codes, where, why in EXCLUDED:
        L.append('| %s | Excluded from MAIN | %s | %s |' % (codes, where, why))
    L += ['', '## 3. Coverage matrix: every standard, subpart, and subskill', '',
          'One row per subskill (a distinct demand of the standard). "(+)" marks an official advanced standard. MAIN IDs are '
          'S<set>-M-Q1 to Q5. "Backward uses" counts questions in other sets that review the standard as a prerequisite.', '',
          '| Standard | Strand | (+) | Subskill | Demand assessed (REVISIT = new Algebra II demand of a shared code) | MAIN sets | Page | Backward uses |',
          '|---|---|---|---|---|---|---:|---:|']
    for code in core + adv:
        _text, subs = standards.STANDARDS[code]
        back = sum(1 for r in by_std[code] if r['section'].startswith('BACKWARD'))
        for sid, desc in subs:
            nums = covers[sid]
            L.append('| %s | %s | %s | %s | %s | %s | %s | %d |' % (
                code, 'CORE' if code in core else 'ADVANCED', '(+)' if hs_courses.official_plus(code) or '(+)' in _text else '',
                sid, desc, ', '.join('S%d' % n for n in nums) or '**none**',
                ', '.join(str(page['S%d-M-Q1' % n]) for n in nums), back))
    missing = [sid for code in core + adv for sid, _ in standards.STANDARDS[code][1] if not covers[sid]]
    L += ['', 'Subskills with no MAIN set: %s. Standards with no MAIN set: %s.' % (
        ', '.join(missing) or 'none', ', '.join(c for c in core + adv if not any(r['section'] == 'MAIN' for r in by_std[c])) or 'none'), '',
          '## 4. Branch map (routing)', '',
          'BACKWARD branches review prerequisites (K-8, Algebra I, Geometry, or the MAIN standard of an earlier Algebra II set, so the '
          'graph has no cycles; "align" is exact or supporting). FORWARD 1 and FORWARD 2 show the progression type, and whether the '
          'standard is the direct next step or the NEAREST RELATED one. FORWARD 2 builds on FORWARD 1 (stated in the export).', '',
          '| Set | Strand | MAIN standard | Backward branches (standard, align) | FORWARD 1 (standard, progression) | FORWARD 2 (standard, progression) |',
          '|---|---|---|---|---|---|']
    for st in sets:
        bk = '; '.join('%s (%s)' % (b['std'], b['meta']['align']) for b in st['back'])
        fw = ['%s (%s%s)' % (st[k]['std'], st[k]['meta']['prog'], ', nearest related' if st[k].get('nearest') else '') for k in ('f1', 'f2')]
        L.append('| S%d %s | %s | %s | %s | %s | %s |' % (st['num'], st['title'], st['strand'], st['std'], bk, fw[0], fw[1]))
    types = collections.Counter(r['type'] for r in recs)
    sec = lambda r: 'BACKWARD' if r['section'].startswith('BACKWARD') else r['section']
    tbs = collections.Counter((sec(r), r['type']) for r in recs)
    ts = sorted(types)
    L += ['', '## 5. Response types', '',
          'sa = short answer; mc = multiple choice (exactly one correct option); tf = true/false. Since version 1.1.0 no question '
          'needs a person or a drawing surface to grade: proofs, derivations, explanations and divisions are multiple choice, and '
          'graphing questions show four candidate graphs labeled A to D.', '',
          '| Section | ' + ' | '.join(ts) + ' |', '|---|' + '---:|' * len(ts)]
    for s in ('MAIN', 'BACKWARD', 'FORWARD 1', 'FORWARD 2'):
        L.append('| %s | %s |' % (s, ' | '.join(str(tbs[(s, t_)]) for t_ in ts)))
    L.append('| Total | %s |' % ' | '.join(str(types[t_]) for t_ in ts))
    L += ['', 'Figures: %d questions carry a figure (coordinate graphs, tables, histograms of supplied simulation results).' % sum(
        1 for r in recs if r['has_figure']), '']
    path = os.path.join(build.GRADE_DIR, 'COVERAGE.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    return path, len(sets)
