"""Write probability_statistics/COVERAGE.md: the course profile, the overlap with the Algebra I, Geometry and Algebra II
collections, a coverage matrix for every standard, subpart and subskill (with the assessed response), the routing (branch)
map of every set, and the response types used.

    python3 question-bank/engine/coverage.py probability_statistics      (dispatches here)
"""
import collections
import json
import os

import build
import hs_courses
import standards

OTHER = [('Algebra I', 'algebra1/Algebra1_Answer_Key.json'), ('Geometry', 'geometry/Geometry_Answer_Key.json'),
         ('Algebra II', 'algebra2/Algebra2_Answer_Key.json')]


def other_mains():
    """HSS codes that other collections in this bank assess in MAIN sets (read from their committed answer keys)."""
    root = os.path.dirname(os.path.dirname(os.path.abspath(build.GRADE_DIR + '/x')))
    out = collections.defaultdict(list)
    for name, rel in OTHER:
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            continue
        for r in json.load(open(path, encoding='utf-8'))['questions']:
            if r['section'] == 'MAIN' and r['set_standard'].startswith('HSS-') and name not in out[r['set_standard']]:
                out[r['set_standard']].append(name)
    return out


def response_kind(r):
    """How a question is answered: a choice among four graphs, another multiple choice, true/false, or a typed answer."""
    if r['type'] == 'mc':
        ch = r['choices'] if isinstance(r['choices'], list) else json.loads(r['choices'] or '[]')
        texts = [c['text'] if isinstance(c, dict) else c for c in ch]
        return 'graph choice' if texts and texts[0] == 'Graph A' else 'MC'
    return {'tf': 'TF', 'sa': 'typed answer'}[r['type']]


def assessed(recs):
    """The assessed response of a set of MAIN questions, with recognition stated honestly."""
    c = collections.Counter(response_kind(r) for r in recs)
    if not c:
        return ''
    parts = ', '.join('%s ×%d' % (k, v) for k, v in sorted(c.items(), key=lambda kv: -kv[1]))
    if c['typed answer'] == sum(c.values()):
        return parts + ' (produces the answer)'
    if c['typed answer'] == 0:
        return parts + ' (recognition: chooses among given options)'
    return parts + ' (mixed: some recognition)'


def run(name):
    recs = json.load(open(build.out_paths()['data'] + '.json', encoding='utf-8'))['questions']
    sets = list(build.all_sets())
    by_std = collections.defaultdict(list)
    for r in recs:
        by_std[r['standard']].append(r)
    page = {r['id']: r['question_page'] for r in recs}
    mains = collections.defaultdict(list)
    for r in recs:
        if r['section'] == 'MAIN':
            mains[int(r['set'])].append(r)
    covers = collections.defaultdict(list)
    for st in sets:
        for sid in st['covers']:
            covers[sid].append(st['num'])
    core, adv = hs_courses.PROB_STAT_CORE, hs_courses.PROB_STAT_ADVANCED
    shared = [c for c in core if c in hs_courses.ALGEBRA_I]
    others = other_mains()
    L = ['# Probability & Statistics coverage report', '',
         'Generated by `probability_statistics/src/coverage_report.py` from the collection data: %d sets, %d questions. Course '
         'placement labels (not grade levels) are used throughout.' % (len(sets), len(recs)), '',
         '## 1. Course profile', '',
         '- **Course:** a high-school Probability & Statistics course (typically taken in grade 10, 11 or 12). No grade level is '
         'assigned; questions carry course-placement labels.',
         '- **CORE strand:** every Common Core High School Statistics & Probability (HSS) standard that is not marked (+): %d '
         'standards, with HSS-ID.B.6 and its lettered parts a, b and c listed separately.' % len(core),
         '- **ADVANCED EXTENSION strand:** every HSS standard marked (+): HSS-CP.B.8, HSS-CP.B.9 and all of HSS-MD (%d standards; '
         'HSS-MD.B.5.a and HSS-MD.B.5.b are separate). Each has its own MAIN set(s); strand = "advanced" in the export.' % len(adv),
         '- **Distinct demands:** standards with several demands are split into subskills (section 3); every subskill is the focus '
         'of at least one MAIN set, so the collection has %d sets for %d standards.' % (len(sets), len(core) + len(adv)),
         '- **Source caveat:** the official pages could not be opened from the authoring environment. Standard codes and wording '
         'were written from the published CCSS and must be spot-checked (README, Assumptions).', '',
         '## 2. Overlap with other collections in this bank', '',
         'The same HSS standards appear in other course collections, because the Common Core traditional pathway spreads '
         'statistics over Algebra I (S-ID), Geometry (S-CP) and Algebra II (S-ID.A.4, S-IC, S-MD.B.6-7). This collection is '
         'self-contained: it does not import, edit or depend on those files. When an S-ID code is used as a prerequisite (backward '
         'branch) it is labeled Algebra I; in MAIN and forward sections every HSS code is labeled Probability & Statistics%s.' % (
             ' (the %d S-ID codes shared with Algebra I say "revisits an Algebra I standard")' % len(shared) if shared else ''), '',
         '| Standard | Also assessed in MAIN sets of | How this collection differs |', '|---|---|---|']
    for code in core + adv:
        if others.get(code):
            L.append('| %s | %s | %s |' % (code, ', '.join(others[code]),
                     'Same standard; new questions and datasets, with the conventions of this course stated on each page.'))
    L += ['', 'Codes not listed above are assessed only in this collection. A school that uses more than one of these collections '
          'can assign the overlapping sets once, in the course where it teaches them.']
    L += ['', '## 3. Coverage matrix: every standard, subpart, and subskill', '',
          'One row per subskill (a distinct demand of the standard). "(+)" marks an official advanced standard. MAIN IDs are '
          'S<set>-M-Q1 to Q5. "Backward uses" counts questions in other sets that review the standard as a prerequisite. "Assessed '
          'response" says how the MAIN questions are actually answered: a typed answer checked by the game, a choice among four '
          'graphs, another multiple choice, or true/false. Where the MAIN questions are choices, the set assesses recognition (for '
          'example choosing the correct plot, design or conclusion), not producing a drawing, a design or a written argument.', '',
          '| Standard | Strand | (+) | Subskill | Demand | Assessed response (MAIN) | MAIN sets | Page | Backward uses |',
          '|---|---|---|---|---|---|---|---:|---:|']
    for code in core + adv:
        _text, subs = standards.STANDARDS[code]
        back = sum(1 for r in by_std[code] if r['section'].startswith('BACKWARD'))
        for sid, desc in subs:
            nums = covers[sid]
            L.append('| %s | %s | %s | %s | %s | %s | %s | %s | %d |' % (
                code, 'CORE' if code in core else 'ADVANCED', '(+)' if hs_courses.official_plus(code) or '(+)' in _text else '',
                sid, desc, assessed([r for n in nums for r in mains[n]]), ', '.join('S%d' % n for n in nums) or '**none**',
                ', '.join(str(page['S%d-M-Q1' % n]) for n in nums), back))
    missing = [sid for code in core + adv for sid, _ in standards.STANDARDS[code][1] if not covers[sid]]
    L += ['', 'Subskills with no MAIN set: %s. Standards with no MAIN set: %s.' % (
        ', '.join(missing) or 'none', ', '.join(c for c in core + adv if not any(r['section'] == 'MAIN' for r in by_std[c])) or 'none'), '',
          '## 4. Branch map (routing)', '',
          'BACKWARD branches review prerequisites (K-8, Algebra I, or the MAIN standard of an earlier set of this collection, so the '
          'graph has no cycles; "align" is exact or supporting). FORWARD 1 and FORWARD 2 show the progression type, and whether the '
          'standard is the direct next step or the NEAREST RELATED one. FORWARD 2 builds on FORWARD 1 (stated in the export).', '',
          '| Set | Strand | MAIN standard | Backward branches (standard, align) | FORWARD 1 (standard, progression) | FORWARD 2 (standard, progression) |',
          '|---|---|---|---|---|---|']
    for st in sets:
        bk = '; '.join('%s (%s)' % (b['std'], b['meta']['align']) for b in st['back'])
        fw = ['%s (%s%s)' % (st[k]['std'], st[k]['meta']['prog'], ', nearest related' if st[k].get('nearest') else '') for k in ('f1', 'f2')]
        L.append('| S%d %s | %s | %s | %s | %s | %s |' % (st['num'], st['title'], st['strand'], st['std'], bk, fw[0], fw[1]))
    types = collections.Counter(r['type'] for r in recs)
    sec = lambda r: 'BACKWARD' if r['section'].startswith('BACKWARD') else r['section']
    tbs = collections.Counter((sec(r), r['type']) for r in recs)
    ts = sorted(types)
    L += ['', '## 5. Response types', '',
          'sa = short answer; mc = multiple choice (exactly one correct option); tf = true/false. Every question is graded '
          'automatically: constructing a display, designing a study, explaining a conclusion and running a simulation are assessed '
          'through the numbers that define the result (counts, quartiles, residuals, simulated outcomes from printed random digits), '
          'a choice among candidate plots, designs or conclusions whose other choices are specific errors, or the decision that '
          'follows from supplied evidence. Every short-answer key was run through the game answer checker itself.', '',
          '| Section | ' + ' | '.join(ts) + ' |', '|---|' + '---:|' * len(ts)]
    for s in ('MAIN', 'BACKWARD', 'FORWARD 1', 'FORWARD 2'):
        L.append('| %s | %s |' % (s, ' | '.join(str(tbs[(s, t_)]) for t_ in ts)))
    L.append('| Total | %s |' % ' | '.join(str(types[t_]) for t_ in ts))
    kinds = collections.Counter(response_kind(r) for r in recs if r['section'] == 'MAIN')
    L += ['', 'MAIN questions by assessed response: %s.' % ', '.join('%s %d' % kv for kv in sorted(kinds.items(), key=lambda kv: -kv[1]))]
    L += ['', 'Figures: %d questions carry a figure (dot plots, histograms, box plots, scatter and residual plots, tables, '
          'random-digit tables).' % sum(
        1 for r in recs if r['has_figure']), '']
    path = os.path.join(build.GRADE_DIR, 'COVERAGE.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    return path, len(sets)
